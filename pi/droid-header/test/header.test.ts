const times = [0, 40, 80, 250, 500, 700, 900, 1100, 1200, 1300, 1500, 1700, 2000, 2400, 2700, 2899, 2900, 4000, Infinity];

test("every line is exactly the width at every width 1–160, state and intro time, and full frames close", () => {
	for (const [name, state] of states) {
		for (let width = 1; width <= 160; width++) {
			for (const t of width % 7 === 0 || width < 45 || width > 95 && width < 110 ? times : [0, 1300, Infinity]) {
				const lines = renderHeader(state, width, t, measure);
				for (const line of lines) assert.equal(cellWidth(line), width, `${name} at ${width} cells, ${t} ms`);
				if (width < COMPACT_WIDTH) assert.equal(lines.length, 1, `${name}: one minimal line at ${width}`);
				if (width >= COMPACT_WIDTH && t === Infinity) {
					const rows = text(lines), bottom = rows.length - 3;
					assert.ok(rows[0].startsWith("┏━ DRD-") && rows[0].endsWith("━┓"), `${name} top at ${width}`);
					assert.ok(rows[bottom].startsWith("┗━") && rows[bottom].endsWith("━┛"), `${name} bottom at ${width}`);
					for (let r = 1; r < bottom; r++) assert.match(rows[r], /^(┃.*┃|┣━ MANIFEST ━+┫)$/u, `${name} side ${r} at ${width}`);
					assert.match(rows.at(-1)!, /interrupt/, `${name} hints at ${width}`);
				}
			}
		}
	}
});

test("only design-system glyphs, ASCII and the measured caller text are drawn", () => {
	for (const width of [40, 72, 104, 140]) for (const t of times) {
		for (const line of renderHeader({ ...MOCK, assignment: "INDUSTRIAL-OS · MAIN" }, width, t, measure)) {
			for (const ch of text([line])[0]) assert.ok(/[\x20-\x7e]/.test(ch) || GLYPHS.includes(ch), `${JSON.stringify(ch)} at ${width}, ${t} ms`);
		}
	}
});

test("unknown values are shown as unknown, never as zero or invented", () => {
	const frame = (state: HeaderState, width = 104) => text(renderHeader(state, width, Infinity, measure)).join("\n");
	const pending = frame(states[1][1]);
	assert.match(pending, /05 MOD {2}-- MODULES/);
	assert.match(pending, /06 SKL {2}-- SKILLS/);
	assert.doesNotMatch(pending, /CTX|LOADING|000 (MODULES|SKILLS)/);
	const failed = frame(states[2][1]);
	assert.match(failed, /┃ {3}MANIFEST UNAVAILABLE · settings\.json: Unexpected token/);
	assert.match(failed, /05 MOD {2}-- MODULES/);
	const unknown = frame(states[4][1]);
	assert.match(unknown, /┏━ DRD-\?\?\?\? /);
	assert.match(unknown, /SES-\?\?\?\?\?\?\?\?│PNE---│PI-1\.4\.0/);
	assert.match(unknown, /04 SCT {2}--/);
	assert.match(unknown, /02 COR {2}-- \/ --/);
	assert.match(unknown, /│ {2}SCRATCH/);
	// The unknown unit number is drawn as decorative question marks.
	const numeral = renderHeader(states[4][1], 104, Infinity, measure)[2];
	assert.ok(cells(numeral).slice(3, 18).filter((c) => c.s !== " ").every((c) => c.fg === ACID_BLACK.decorative));
	const empty = frame(states[3][1]);
	assert.match(empty, /CTX {2}00/);
	assert.match(empty, /EXT {2}00/);
	assert.doesNotMatch(empty, /▪/);
	assert.match(empty, /05 MOD {2}000 MODULES/);
	// Failures are never animated or scrambled, and use the critical role with the word.
	const failRow = renderHeader(states[2][1], 104, 1250, measure).find((line) => text([line])[0].includes("UNAVAILABLE"))!;
	assert.ok(cells(failRow).some((c) => c.s === "M" && c.fg === ACID_BLACK.critical));
});

