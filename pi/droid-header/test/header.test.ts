test("the full layout from 100 columns, compact from 40, one minimal line below", () => {
	const at = (width: number) => text(renderHeader(MOCK, width, Infinity, measure));
	assert.equal(FULL_WIDTH, 100);
	assert.equal(COMPACT_WIDTH, 40);
	assert.match(at(100)[3], /\\\|\/ {6}┃$/);
	const compact = at(99);
	assert.doesNotMatch(compact.join("\n"), /[▀▄█]|\\\|\/|•/);
	assert.deepEqual(compact.slice(2, 8).map((row) => row.slice(4, 10)), ["01 CLS", "02 COR", "03 FRM", "04 SCT", "05 MOD", "06 SKL"]);
	assert.match(compact[9], /^┃ {3}DEPLOYED 09:30:00 /);
	assert.match(compact[10], /^┃ {3}ASSIGNMENT {2}INDUSTRIAL-OS · MAIN/);
	assert.match(compact[12], /^┣━ MANIFEST ━+┫$/);
	// Hints that do not fit are dropped whole from the end, never a later one after a gap.
	const narrowHints = renderHeader({ ...MOCK, hints: [["esc", "interrupt"], ["a-very-long-key-name", "x".repeat(30)], ["/", "commands"]] }, 60, Infinity, measure);
	assert.equal(text(narrowHints).at(-1)!.trimEnd(), " esc interrupt");
	assert.deepEqual(at(39), ["DRD-C0DE ● PI-1.4.0 · 014 MOD · 012 SKL"]);
	assert.deepEqual(at(20), ["DRD-C0DE ● PI-1.4.0…"]);
	assert.deepEqual(at(1), ["…"]);
	assert.deepEqual(renderHeader(MOCK, 0, Infinity, measure), []);
});

test("the intro follows the mock's timeline and settles at 2.9 s", () => {
	const at = (t: number) => renderHeader(MOCK, 104, t, measure);
	const row = (t: number, r: number) => text(at(t))[r];
	assert.equal(introEnd(MOCK), INTRO_MS);
	assert.equal(INTRO_MS, 2900);
	// Nothing but the start of the frame at 0 ms; the lamp blinks ○/● every 80 ms until 1.5 s, then holds.
	assert.match(row(0, 0), /^ +$/);
	assert.match(row(600, 0), /○ ━┓$/);
	assert.match(row(680, 0), /● ━┓$/);
	assert.match(row(1600, 0), /● ━┓$/);
	// Plates warm through accent 25/50/75% to acid in 60 ms steps, plate i starting at 500 + 170i ms.
	const plateBg = (t: number) => cells(at(t)[2])[22].bg;
	assert.deepEqual([400, 500, 560, 620, 680].map(plateBg), [ACID_BLACK.structural, SIGNAL_COLORS.accent25, SIGNAL_COLORS.accent50, SIGNAL_COLORS.accent75, ACID_BLACK.accent]);
	// Values decode: blank, scramble glyphs changing every 70 ms, then the true text by 500 ms after they start.
	assert.equal(row(700, 2).slice(31, 45).trim(), "");
	assert.notEqual(row(900, 2).slice(31, 45), "PI AGENT DROID");
	assert.equal(row(1200, 2).slice(31, 45), "PI AGENT DROID");
	assert.equal(DECODE_STEP_MS, 70);
	// The starburst spins in 70 ms steps from 1.3 s and rests on * once settled.
	assert.deepEqual([1330, 1400, 1470, 1540].map((t) => row(t, 4).slice(95, 96)), ["\\", "|", "/", "-"]);
	assert.equal(row(Infinity, 4).slice(95, 96), "*");
	// The manifest prints hold by hold; a hold's plate flashes acid for 120 ms as it starts.
	assert.equal(cells(at(1250)[10])[3].bg, ACID_BLACK.accent);
	assert.equal(cells(at(1400)[10])[3].bg, ACID_BLACK.secondary);
	assert.doesNotMatch(row(1250, 13), /SKL/);
	// Key hints arrive last; nothing ever says LOADING or draws a progress bar.
	assert.doesNotMatch(text(at(2400)).at(-1)!, /interrupt/);
	assert.match(text(at(2899)).at(-1)!, /^ esc interrupt · ctrl\+c clear · \/ commands · ! bash *$/);
	for (const t of times) assert.doesNotMatch(text(at(t)).join("\n"), /LOADING|PROGRESS/);
	assert.deepEqual(text(at(INTRO_MS)), text(at(Infinity)));
});

test("a manifest that arrives mid-intro prints from its arrival and extends the intro boundedly", () => {
	const late: HeaderState = { ...MOCK, manifestAt: 2500 };
	assert.equal(introEnd(late), 2500 + 1500 + 200);
	assert.doesNotMatch(text(renderHeader(late, 104, 2400, measure)).join("\n"), /CTX/);
	assert.match(text(renderHeader(late, 104, 2600, measure)).join("\n"), /CTX/);
	assert.deepEqual(text(renderHeader(late, 104, introEnd(late), measure)), text(renderHeader(MOCK, 104, Infinity, measure)));
	assert.equal(introEnd({ ...MOCK, manifest: { status: "pending" } }), INTRO_MS);
});
