const cells = (line: Line) => line.flatMap((span) => [...span.text].map((s) => ({ s, fg: span.fg, bg: span.bg })));
const text = (lines: Line[]) => lines.map((line) => line.map((span) => span.text).join(""));
const cellWidth = (line: Line) => measure(line.map((span) => span.text).join(""));

test("the settled frame at 104 columns matches the approved mock cell for cell, apart from the seeded barcode", () => {
	const lines = renderHeader(MOCK, 104, Infinity, measure);
	assert.equal(lines.length, GOLDEN_TEXT.length);
	const rng = random(MOCK.seed), bars = Array.from({ length: 15 }, () => pick(rng, ["▌", "▐", "█", "▏", "▎", "▍"])).join("");
	lines.forEach((line, r) => {
		const row = cells(line);
		assert.equal(row.length, 104, `row ${r} width`);
		const expected = r === 5 || r === 6 ? GOLDEN_TEXT[r].replace("#".repeat(15), bars) : GOLDEN_TEXT[r];
		assert.equal(row.map((c) => c.s).join("").trimEnd(), expected, `row ${r} text`);
		const style = GOLDEN_STYLE[r].padEnd(104, ".");
		row.forEach((cell, c) => {
			const key = style[c];
			if (key === ".") assert.equal(cell.s === " " ? cell.bg : "glyph", ACID_BLACK.field, `row ${r} col ${c} is a space on the field`);
			else assert.deepEqual([cell.fg, cell.bg], STYLE_KEY[key], `row ${r} col ${c} style ${key}`);
		});
	});
});

