// Writes the mod's copy of the design system's sidebar vocabulary and the drawn marks it ships.
// A mod folder is copied into ~/.config/herdr-app/mods as it is and cannot import a package, so the copy and the
// files are committed; test/industrial-os-vocabulary.test.mjs fails when they differ from the design system.
// Run from herdr/: node scripts/sync-vocabulary.mjs
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { markFiles } from '@industrial-os/design-system/foundation/sidebar-vocabulary';

const source = new URL('../../design-system/foundation/sidebar-vocabulary.mjs', import.meta.url);
const mod = new URL('../mods/industrial-os/', import.meta.url);
export const HEADER = '// A copy of design-system/foundation/sidebar-vocabulary.mjs, written by herdr/scripts/sync-vocabulary.mjs.\n// Change the design system, then run the script; do not edit this file.\n';
/** The design-system module without its leading comment. */
export const body = (text) => text.replace(/^(\/\/.*\n)+/, '');

if (process.argv[1] === new URL(import.meta.url).pathname) {
  await writeFile(new URL('vocabulary.js', mod), HEADER + body(await readFile(source, 'utf8')));
  const marks = new URL('marks/', mod);
  await mkdir(marks, { recursive: true });
  const files = markFiles();
  for (const name of await readdir(marks)) if (!files.some(([file]) => file === name)) await unlink(new URL(name, marks));
  for (const [name, text] of files) await writeFile(new URL(name, marks), text);
  console.log(`vocabulary.js and ${files.length} marks written`);
}
